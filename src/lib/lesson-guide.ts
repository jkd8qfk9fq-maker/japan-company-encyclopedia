import type { QuestionTable } from "@/lib/lesson-questions";

/**
 * The learn block of every micro-lesson (JCE-091): what is read before the questions are asked. The
 * JCE-090 course asked its questions after two paragraphs of prose, and the operator — taking the course
 * — found that the questions arrived before anything had been taught: "先に学習がないために、急に問題に
 * 飛んでしまうと混乱する". So each lesson now opens with the stumbling point it removes, teaches the
 * concept (the lesson's own prose, plus an authored diagram of the statement's form where a picture
 * carries it), and then reads the real thing together — the excerpt table a bound question already
 * carries, walked through with guidance — before the unchanged questions check the reading.
 *
 * Everything authored here is general method: the form of a statement, never a company's fact. The
 * diagrams name items and sections, and hold no figures. A figure appears in a lesson only inside a
 * bound question's table, printed as filed with its citation; the binding in src/lib/micro-lessons.ts
 * lifts that table into the walkthrough, so the guided reading and the question read the same excerpt.
 * Where no bound question carries a table, a lesson may name an authored excerpt of the form itself
 * (guideTable) — again items and sections only, no amounts.
 */
export type LessonGuide = {
  /** The moment this lesson unsticks: where a first reader stops being able to read. One or two sentences. */
  stumble: string;
  /** The minutes the whole lesson — learn block and questions — honestly takes (JCE-091). */
  minutes: number;
  /** An authored diagram of the statement's form, shown with the concept prose. Structure only, no figures. */
  diagram?: QuestionTable;
  /** The guided reading: where to look in the real thing, in order. Read before the questions. */
  guide: string[];
  /** An authored excerpt of the form, for the walkthrough of a lesson no bound question gives a table to. */
  guideTable?: QuestionTable;
  /**
   * Whether the walkthrough lifts a bound question's table (default true). A lesson whose reading is
   * specific to one statement opts out when the excerpt that binds may be the other statement's summary —
   * which variant of a row-finding question binds is a property of the data, not of the lesson.
   */
  liftGuideTable?: boolean;
};

